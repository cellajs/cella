import { promises as fsp } from 'node:fs';
import path from 'node:path';
import { localeFilesOf, toRuntimeNamespaces } from 'shared/utils/locale-namespaces';
import type { Plugin } from 'vite';

interface LocalesPluginOptions {
  /** Source directory holding `<lng>/<ns>.json` files and the namespace manifest. */
  srcDir: string;
  /** Cache directory i18n Ally reads (locales/README.md). */
  cacheDir: string;
}

/** English holds every key, so it types `t()`. */
const typesLanguage = 'en';
const typesFile = 'resources.gen.d.ts';

type Resources = Record<string, string>;

const readLanguage = async (srcDir: string, language: string): Promise<Record<string, Resources>> => {
  const entries = await fsp.readdir(path.join(srcDir, language), { withFileTypes: true }).catch(() => []);
  const names = entries.filter((entry) => entry.isFile() && entry.name.endsWith('.json')).map((entry) => entry.name);
  const files = await Promise.all(
    names.map(async (name) => [path.basename(name, '.json'), JSON.parse(await fsp.readFile(path.join(srcDir, language, name), 'utf8'))] as const),
  );
  return Object.fromEntries(files);
};

/** Rewrites a generated file only when its content changes, so watchers and incremental typechecks stay idle. */
const writeIfChanged = async (file: string, content: string) => {
  if ((await fsp.readFile(file, 'utf8').catch(() => undefined)) === content) return;
  await fsp.writeFile(file, content, 'utf8');
};

/**
 * Writes `resources.gen.d.ts`: each runtime namespace typed as its English texts, so `t('c:accept')` types as
 * `"Accept"`. The JSON imports keep a key added since the last generation typed as `string`.
 */
export const writeLocaleTypes = async (srcDir: string) => {
  const files = await readLanguage(srcDir, typesLanguage);
  const identifier = (file: string) => `${typesLanguage}${file.charAt(0).toUpperCase()}${file.slice(1)}`;
  const imports = Object.keys(files)
    .sort()
    .map((file) => `import type ${identifier(file)} from './${typesLanguage}/${file}.json';`);
  const namespaces = Object.entries(toRuntimeNamespaces(files))
    .sort(([a], [b]) => (a < b ? -1 : 1))
    .map(([namespace, resources]) => {
      const sources = localeFilesOf(namespace).filter((file) => file in files);
      const texts = Object.keys(resources)
        .sort()
        .map((key) => `    ${JSON.stringify(key)}: ${JSON.stringify(resources[key])};`);
      return [`  ${namespace}: ${[...sources.map((file) => `typeof ${identifier(file)}`), '{'].join(' & ')}`, ...texts, '  };'].join('\n');
    });
  const content = [
    '// Generated by frontend/vite/locales-plugin.ts from locales/en and locales/namespaces.json: do not edit.',
    '',
    ...imports,
    '',
    '/** Each runtime namespace as its English texts. */',
    'export interface LocaleResources {',
    ...namespaces,
    '}',
    '',
  ].join('\n');
  await writeIfChanged(path.join(srcDir, typesFile), content);
};

/**
 * Writes the literal-typed resources on every start and build, and in dev the i18n Ally cache: each language's
 * runtime namespaces, since no raw file maps to a merged one. The app itself bundles and lazy-loads locales as
 * modules (lib/i18n-locales.ts).
 */
export function localesPlugin({ srcDir, cacheDir }: LocalesPluginOptions): Plugin {
  const syncLanguage = async (language: string) => {
    const namespaces = toRuntimeNamespaces(await readLanguage(srcDir, language));
    await fsp.mkdir(path.join(cacheDir, language), { recursive: true });
    await Promise.all(
      Object.entries(namespaces).map(([namespace, data]) =>
        fsp.writeFile(path.join(cacheDir, language, `${namespace}.json`), JSON.stringify(data, null, 2), 'utf8'),
      ),
    );
  };

  const buildCache = async () => {
    await fsp.rm(cacheDir, { recursive: true, force: true });
    const entries = await fsp.readdir(srcDir, { withFileTypes: true }).catch(() => []);
    await Promise.all(entries.filter((entry) => entry.isDirectory() && !entry.name.startsWith('.')).map((entry) => syncLanguage(entry.name)));
  };

  return {
    name: 'locales',
    buildStart: () => writeLocaleTypes(srcDir),
    async configureServer(server) {
      await buildCache();
      server.watcher.add(srcDir);
      server.watcher.on('change', (file) => {
        const [language, name, ...deeper] = path.relative(srcDir, file).split(path.sep);
        // Only `<lng>/<ns>.json`: the manifest is read once, at start
        if (language === '..' || !name?.endsWith('.json') || deeper.length > 0) return;
        const updates = [syncLanguage(language), ...(language === typesLanguage ? [writeLocaleTypes(srcDir)] : [])];
        Promise.all(updates).catch((error) => console.error('[locales] cache sync failed', error));
      });
    },
  };
}
