import { createXRoutes, errors, json, jsonBody, xRoute } from '#/core/x-routes';
import { stepUpGuard, userGuard } from '#/middlewares/guard';
import { bulkPointsLimiter, singlePointsLimiter, uploadTokenLimiter } from '#/middlewares/rate-limiter/limiters';
import { mockConnectedApp, mockPaginatedInvitationsResponse } from '#/modules/me/me-mocks';
import {
  connectedAppParamSchema,
  connectedAppSchema,
  meAuthDataSchema,
  mePendingInvitationSchema,
  meSchema,
  myInvitationParamSchema,
  sessionBaseSchema,
  toggleMfaBodySchema,
  updateMeBodySchema,
  uploadTokenQuerySchema,
  uploadTokenSchema,
} from '#/modules/me/me-schema';
import { membershipBaseSchema } from '#/modules/memberships/memberships-schema';
import { userSchema } from '#/modules/user/user-schema';
import { batchResponseSchema, entityWithTypeSchema, idsBodySchema, pageQuerySchema, paginationSchema } from '#/schemas';
import { channelBaseSchema } from '#/schemas/entity-base';

export const meRoutes = createXRoutes(['me', 'cella'], {
  getMe: xRoute({
    method: 'get',
    path: '/',
    xGuard: [userGuard],
    xAnonymous: true,
    summary: 'Get self',
    description: 'Returns the current user.',
    responses: { 200: json('User', meSchema) },
  }),
  listMyInvitations: xRoute({
    method: 'get',
    path: '/invitations',
    xGuard: [userGuard],
    xAnonymous: true,
    summary: 'Get list of invitations',
    description: 'Returns a list of pending memberships with entity data.',
    request: { query: pageQuerySchema },
    responses: { 200: json('Invitations pending', paginationSchema(mePendingInvitationSchema), mockPaginatedInvitationsResponse()) },
  }),
  acceptInvitation: xRoute({
    method: 'post',
    path: '/invitations/{invitationId}/~accept',
    xGuard: [userGuard],
    xRateLimiter: [singlePointsLimiter],
    summary: 'Accept membership invitation',
    description:
      "Makes the caller a member of the invited channel, or leaves a membership they hold as it is. Returns the invitation's organization.",
    request: { params: myInvitationParamSchema },
    responses: { 200: json("The invitation's organization", channelBaseSchema), ...errors(404, 409) },
  }),
  rejectInvitation: xRoute({
    method: 'post',
    path: '/invitations/{invitationId}/~reject',
    xGuard: [userGuard],
    xRateLimiter: [singlePointsLimiter],
    summary: 'Reject membership invitation',
    description: "Declines the invitation, and its emailed link stops working. Returns the invitation's organization.",
    request: { params: myInvitationParamSchema },
    responses: { 200: json("The invitation's organization", channelBaseSchema), ...errors(404, 409) },
  }),
  updateMe: xRoute({
    method: 'patch',
    path: '/',
    xGuard: [userGuard],
    xAnonymous: true,
    xRateLimiter: [singlePointsLimiter],
    summary: 'Update self',
    description: 'Updates the current user.',
    request: { body: jsonBody(updateMeBodySchema) },
    responses: { 200: json('User', userSchema), ...errors(409) },
  }),
  deleteMe: xRoute({
    method: 'delete',
    path: '/',
    xGuard: [userGuard, stepUpGuard],
    xRateLimiter: [singlePointsLimiter],
    summary: 'Delete self',
    description:
      "Deletes the current user. This also removes the user's memberships (cascade) and sets references to the user to null where applicable.",
    responses: { 204: { description: 'User deleted' }, ...errors(409) },
  }),
  getMyAuth: xRoute({
    method: 'get',
    path: '/auth',
    xGuard: [userGuard],
    xAnonymous: true,
    summary: 'Get auth data',
    description: 'Returns authentication related data of current user, including sessions, passkeys, TOTP and the enabled sign-in providers.',
    responses: { 200: json('Sign-in methods and sessions', meAuthDataSchema) },
  }),
  revokeMySessions: xRoute({
    method: 'post',
    path: '/sessions/~revoke',
    xGuard: [userGuard],
    xRateLimiter: [bulkPointsLimiter],
    summary: 'Revoke sessions',
    description:
      'Revokes sessions of the current user by id. The rows stay for the audit trail and the sessions list shows them as revoked for the retention period. Revoking the current session signs out; revoking any other needs a recent proof of presence on this session (step-up).',
    request: { body: jsonBody(idsBodySchema()) },
    responses: { 200: json('Sessions were revoked', batchResponseSchema(sessionBaseSchema)) },
  }),
  leaveMembership: xRoute({
    method: 'post',
    path: '/memberships/~leave',
    xGuard: [userGuard],
    xRateLimiter: [singlePointsLimiter],
    summary: 'Leave channel',
    description: 'Removes the current user from a channel entity they are a member of.',
    request: { body: jsonBody(entityWithTypeSchema) },
    responses: { 204: { description: 'Membership removed' }, ...errors(404, 409) },
  }),
  getUploadToken: xRoute({
    method: 'get',
    path: '/upload-token',
    xGuard: [userGuard],
    xAnonymous: true,
    xRateLimiter: [uploadTokenLimiter],
    summary: 'Get upload token',
    description:
      "Generates and returns an upload token for uploading files or images, scoped to the current user and organization. The upload template decides the bucket: avatars, covers and newsletter images are public, attachments private. An attachment token needs an organization the user may create attachments in, and is refused at its tenant's attachment quota before any file is stored. Only a system admin gets a newsletter image token.",
    request: { query: uploadTokenQuerySchema },
    responses: {
      200: json(
        'Upload token\n\nIts storage prefix names the organization, when given, and the user; a newsletter image goes under the system prefix.',
        uploadTokenSchema,
      ),
      ...errors(403, 404),
    },
  }),
  toggleMfa: xRoute({
    method: 'post',
    path: '/~toggle-mfa',
    xGuard: [userGuard, stepUpGuard],
    xRateLimiter: [singlePointsLimiter],
    summary: 'Toggle MFA',
    description: 'Enable or disable multifactor authentication for the current user. Needs a session stepped up with a passkey or TOTP.',
    request: { body: jsonBody(toggleMfaBodySchema) },
    responses: { 200: json('User', userSchema) },
  }),
  listMyMemberships: xRoute({
    method: 'get',
    path: '/memberships',
    xGuard: [userGuard],
    xAnonymous: true,
    summary: 'Get my memberships',
    description: 'Returns the memberships of the current user across all channel entities.',
    request: { query: pageQuerySchema },
    responses: { 200: json('User memberships', paginationSchema(membershipBaseSchema)) },
  }),
  listConnectedApps: xRoute({
    method: 'get',
    path: '/connected-apps',
    xGuard: [userGuard],
    xAnonymous: true,
    summary: 'Get connected apps',
    description: 'Lists the OAuth clients the user consented to (MCP clients, registered apps) with their scopes.',
    request: { query: pageQuerySchema },
    responses: { 200: json('Connected apps', paginationSchema(connectedAppSchema), { results: [mockConnectedApp()], totalSize: 1 }) },
  }),
  deleteConnectedApp: xRoute({
    method: 'delete',
    path: '/connected-apps/{connectedAppId}',
    xGuard: [userGuard],
    xRateLimiter: [singlePointsLimiter],
    summary: 'Revoke connected app',
    description: 'Revokes a consent: the grant and every token issued under it are deleted.',
    request: { params: connectedAppParamSchema },
    responses: { 204: { description: 'Consent revoked' }, ...errors(404) },
  }),
});
